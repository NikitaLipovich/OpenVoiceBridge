static const char *reset_reason_name(esp_reset_reason_t r)
{
    switch (r) {
    case ESP_RST_POWERON:   return "POWERON";
    case ESP_RST_EXT:       return "EXT";
    case ESP_RST_SW:        return "SW";
    case ESP_RST_PANIC:     return "PANIC";
    case ESP_RST_INT_WDT:   return "INT_WDT";
    case ESP_RST_TASK_WDT:  return "TASK_WDT";
    case ESP_RST_WDT:       return "WDT";
    case ESP_RST_DEEPSLEEP: return "DEEPSLEEP";
    case ESP_RST_BROWNOUT:  return "BROWNOUT";
    case ESP_RST_SDIO:      return "SDIO";
    default:                return "UNKNOWN";
    }
}

void app_main(void)
{
#ifdef BENCH_MAC_PATCH
    // A phone keeps per-address workarounds that survive unpairing. A shifted address lets the bench start clean
    // on such a phone without resetting its Bluetooth settings. The factory address stays in the efuse.
    uint8_t bench_mac[6];
    ESP_ERROR_CHECK(esp_efuse_mac_get_default(bench_mac));
    bench_mac[BENCH_MAC_PATCH / 256] = (uint8_t)(bench_mac[BENCH_MAC_PATCH / 256] + BENCH_MAC_PATCH % 256);
    ESP_ERROR_CHECK(esp_base_mac_addr_set(bench_mac));
#endif
#ifdef BENCH_BROWNOUT_RESET
    // Diagnostic: let a supply sag reset the chip with a distinct reason code,
    // since POWERON alone cannot tell a sag from an EN pulse.
    brownout_hal_config_t bod = {
        .threshold = BENCH_BROWNOUT_RESET - 1, .enabled = true, .reset_enabled = true,
        .flash_power_down = false, .rf_power_down = false,
    };
    brownout_hal_config(&bod);
#endif
    esp_reset_reason_t reset_reason = esp_reset_reason();
    ESP_LOGI(TAG, "BOOT reset_reason=%s code=%d", reset_reason_name(reset_reason), (int)reset_reason);
    ESP_LOGI(TAG, "=== LyraT Phone Stream — All Phases ===");

    // NVS
    esp_err_t ret = nvs_flash_init();
    if (ret == ESP_ERR_NVS_NO_FREE_PAGES ||
        ret == ESP_ERR_NVS_NEW_VERSION_FOUND) {
        ESP_ERROR_CHECK(nvs_flash_erase());
        ret = nvs_flash_init();
    }
    ESP_ERROR_CHECK(ret);

    ESP_LOGI(TAG, "Free heap: %"PRIu32" bytes", esp_get_free_heap_size());

    s_cmd_mutex = xSemaphoreCreateMutex();
    configASSERT(s_cmd_mutex);

    // Ring buffers — BT path
    s_rb_call_rx = xRingbufferCreate(FRAME_BYTES_MONO * RINGBUF_FRAMES,
                                     RINGBUF_TYPE_BYTEBUF);
    s_rb_mic_tx  = xRingbufferCreate(FRAME_BYTES_MONO * RINGBUF_FRAMES,
                                     RINGBUF_TYPE_BYTEBUF);

    if (!s_rb_call_rx || !s_rb_mic_tx) {
        ESP_LOGE(TAG, "Ring buffer alloc failed");
        abort();
    }

    // AEC
    lyrat_aec_init();
    spectral_ns_init();
    voice_ns_init();

    // Audio: I2C + I2S + ES8388
    ESP_ERROR_CHECK(audio_init());

    // Bluetooth
#ifdef BENCH_NO_BT
    ESP_LOGW(TAG, "BENCH: Bluetooth disabled");
#else
    ESP_ERROR_CHECK(bt_init());
#endif

    // Tasks on Core 1 (Core 0 = BT stack)
    xTaskCreatePinnedToCore(i2s_tx_task,       "i2s_tx",    4096, NULL, 15, NULL, 1);
    xTaskCreatePinnedToCore(mic_rx_task,        "mic_rx",    8192, NULL, 14, NULL, 1);
    xTaskCreatePinnedToCore(console_task,       "console",   4096, NULL,  5, NULL, 1);
#ifndef BENCH_NO_CTL_UART  // goal 057 #004: measures the link without this task
    xTaskCreatePinnedToCore(ctl_uart_task,      "ctl_uart",  4096, NULL,  4, NULL, 1);
#endif

    ESP_LOGI(TAG, "Free heap after init: %"PRIu32" bytes", esp_get_free_heap_size());
    ESP_LOGI(TAG, "Pair Android with '%s', type 'help' in monitor for DSP control",
             BT_DEVICE_NAME);

    while (1) {
        vTaskDelay(pdMS_TO_TICKS(10000));
        ESP_LOGI(TAG, "SCO=%s heap=%"PRIu32,
                 s_sco_active ? "active" : "idle",
                 esp_get_free_heap_size());
        if (s_sco_active) {
            sco_stats_log("live");
            esp_hf_client_pkt_stat_nums_get(s_sco_handle);
        }
    }
}
