static void gap_cb(esp_bt_gap_cb_event_t event, esp_bt_gap_cb_param_t *param)
{
    switch (event) {
    case ESP_BT_GAP_AUTH_CMPL_EVT:
        if (param->auth_cmpl.stat == ESP_BT_STATUS_SUCCESS)
            ESP_LOGI(TAG_BT, "Paired: '%s'", param->auth_cmpl.device_name);
        else
            ESP_LOGW(TAG_BT, "Pairing failed: %d", param->auth_cmpl.stat);
        break;

    case ESP_BT_GAP_ACL_CONN_CMPL_STAT_EVT:
        ESP_LOGI(TAG_BT, "ACL UP stat=0x%x handle=0x%x",
                 param->acl_conn_cmpl_stat.stat, param->acl_conn_cmpl_stat.handle);
        link_power_acl(param->acl_conn_cmpl_stat.stat == 0, param->acl_conn_cmpl_stat.handle);
        break;

    case ESP_BT_GAP_MODE_CHG_EVT:
        link_power_mode(param->mode_chg.mode == ESP_BT_PM_MD_ACTIVE);
        break;

    case ESP_BT_GAP_ACL_DISCONN_CMPL_STAT_EVT:
        link_power_acl(false, param->acl_disconn_cmpl_stat.handle);
        s_acl_reason = param->acl_disconn_cmpl_stat.reason;
        ESP_LOGW(TAG_BT, "ACL DOWN reason=0x%x handle=0x%x",
                 param->acl_disconn_cmpl_stat.reason, param->acl_disconn_cmpl_stat.handle);
        break;

    case ESP_BT_GAP_CFM_REQ_EVT:
        ESP_LOGI(TAG_BT, "SSP confirm %06"PRIu32" — auto-accept",
                 param->cfm_req.num_val);
        esp_bt_gap_ssp_confirm_reply(param->cfm_req.bda, true);
        break;

    case ESP_BT_GAP_KEY_NOTIF_EVT:
        ESP_LOGI(TAG_BT, "SSP passkey %06"PRIu32, param->key_notif.passkey);
        break;

    case ESP_BT_GAP_PIN_REQ_EVT: {
        esp_bt_pin_code_t pin = {'0', '0', '0', '0'};
        esp_bt_gap_pin_reply(param->pin_req.bda, true, 4, pin);
        break;
    }

    default:
        ESP_LOGD(TAG_BT, "GAP event %d", event);
        break;
    }
}

