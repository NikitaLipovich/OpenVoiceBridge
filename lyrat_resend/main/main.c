// Share of the time of one core per task since the last call, in tenths of a percent.
static void print_cpu(void)
{
    enum { MAX_TASKS = 28 };
    static TaskStatus_t now[MAX_TASKS];
    static UBaseType_t last_id[MAX_TASKS];
    static uint32_t last_run[MAX_TASKS];
    static uint32_t last_total;
    uint32_t total = 0;
    UBaseType_t count = uxTaskGetSystemState(now, MAX_TASKS, &total);
    uint32_t span = total - last_total;
    for (UBaseType_t i = 0; i < count; i++) {
        uint32_t before = 0;
        for (int j = 0; j < MAX_TASKS; j++) {
            if (last_id[j] == now[i].xTaskNumber) before = last_run[j];
        }
        CMD_OUT("cpu %s %"PRIu32" stack_free=%"PRIu32, now[i].pcTaskName,
                span ? (uint32_t)(((uint64_t)(now[i].ulRunTimeCounter - before) * 1000) / span) : 0,
                (uint32_t)now[i].usStackHighWaterMark);
    }
    for (int j = 0; j < MAX_TASKS; j++) {
        last_id[j] = j < (int)count ? now[j].xTaskNumber : 0;
        last_run[j] = j < (int)count ? now[j].ulRunTimeCounter : 0;
    }
    last_total = total;
    CMD_OUT("cpu heap internal=%u min=%u psram=%u", (unsigned)heap_caps_get_free_size(MALLOC_CAP_INTERNAL),
            (unsigned)heap_caps_get_minimum_free_size(MALLOC_CAP_INTERNAL),
            (unsigned)heap_caps_get_free_size(MALLOC_CAP_SPIRAM));
}

