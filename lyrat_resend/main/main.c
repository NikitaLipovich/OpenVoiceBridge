static volatile uint16_t s_sco_handle;

// Frame status counters and the cost of a frame on the Bluetooth task
static volatile uint32_t s_rx_frames, s_rx_bad, s_rx_undecoded, s_rx_concealed, s_rx_zero;
static volatile uint32_t s_cb_count, s_cb_max_us;
static volatile uint64_t s_cb_total_us;
static volatile int64_t  s_sco_open_us;
static volatile int      s_plc_on = 1;     // "plc 0" passes frames on as they came, for a comparison on the bench
static volatile uint32_t s_mic_dropped, s_mic_level_min, s_mic_level_max;

// mSBC carries a two bit frame number in its H2 header: a jump in it shows a frame missing or doubled before this board,
// which no status flag reports. The last few events go out when the channel closes, not while it runs.
#define SCO_EVENTS 24
typedef struct {
    uint32_t frame;
    char     kind;      // B bad, U undecoded, J number jumped
    uint8_t  value;     // J: the step, 1 would be normal
} sco_event_t;
static sco_event_t       s_sco_events[SCO_EVENTS];
static volatile uint32_t s_sco_event_count, s_rx_sn_jumps;

static void sco_event(char kind, uint8_t value)
{
    sco_event_t *e = &s_sco_events[s_sco_event_count++ % SCO_EVENTS];
    e->frame = s_rx_frames;
    e->kind  = kind;
    e->value = value;
}

