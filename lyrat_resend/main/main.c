//
// The stack hands over one raw frame with its status and takes raw frames back. The pipeline always runs at 16 kHz.
// mSBC frames decode to 16 kHz PCM; CVSD frames are 8 kHz PCM and get resampled here, at the Bluetooth boundary,
// through one half-band FIR. A lost or broken frame is concealed before any of that, in the rate of its codec.
//
// Outgoing frames are paced by incoming ones: the link takes one frame per interval, and the stack drops frames without
// a word when its queue overflows, so sending all that is available would only build up a delay.

#define HB_ODD_TAPS   12        // odd half of a 47 tap half-band FIR, sums to 0.25 (Q15)
#define HB_UP_HIST    (2 * HB_ODD_TAPS)
#define HB_DOWN_HIST  (4 * HB_ODD_TAPS - 1)
#define HB_CENTER     (2 * HB_ODD_TAPS - 1)
#define BT_CHUNK_8K   120       // 8 kHz samples handled per pass
#define CVSD_FRAME    60        // 8 kHz samples per concealed frame, 7.5 ms, whatever size the packets have
#define TX_CREDIT_MAX 2         // frames to catch up per incoming frame after the microphone came late
// A CVSD frame of exact zeros with a good status, in the middle of a loud signal, is a loss the status does not show
// (goal 045 #002). Past this many in a row it is taken as the real silence it then is.
#define CVSD_ZERO_FRAMES_MAX 2
#define CVSD_LOUD_SUM        (CVSD_FRAME * 64)      // sum of magnitudes over a frame, far under any speech
// The microphone delivers 15 ms at a time and the link takes 7.5 ms every 7.5 ms, so nothing may be sent before the ring
// holds a margin: with an empty ring any delay of the mic task is a frame missing on the air (goal 045, up direction).
#define TX_MIC_FRAME_BYTES  240                         // 7.5 ms at 16 kHz, whatever the codec
#define TX_START_BYTES      (8 * TX_MIC_FRAME_BYTES)    // 60 ms, half of the ring
#define TX_REFILL_BYTES     (4 * TX_MIC_FRAME_BYTES)    // after the ring ran dry

static const int16_t s_hb_odd[HB_ODD_TAPS] = {
    10379, -3318, 1830, -1150, 750, -489, 311, -189, 107, -55, 23, -7
};

static volatile bool s_bt_8k        = false;   // set from the connected state of AUDIO_STATE_EVT
static volatile bool s_sco_reset    = false;   // consumed by the callback that owns the state
static volatile uint16_t s_tx_frame_bytes;     // encoded frame size the link asks for

// Loss counters of the current SCO link
