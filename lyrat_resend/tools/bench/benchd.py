def make_handler(svc):
    admin = BENCH / "benchd_admin.html"

    # --- one function per row of ROUTES; (method, path) -> function(handler, q_or_body) -> (code, obj[, ctype])
    def page(h, q):
        return 200, admin.read_bytes(), "text/html; charset=utf-8"

    def favicon(h, q):
        return 204, None

    def get_logs(h, q):
        return 200, svc.store.logs(parse_time(q.get("from")), parse_time(q.get("to")), q.get("board"), q.get("grep"),
                                   int(q.get("limit", 2000)))

    def get_tail(h, q):
        return 200, svc.store.tail(int(q.get("after", 0)), q.get("board"), q.get("grep"), int(q.get("limit", 500)))

    def get_events(h, q):
        return 200, svc.store.query_events(parse_time(q.get("from")), parse_time(q.get("to")), q.get("type"),
                                           int(q.get("limit", 1000)))

    def get_whoami(h, q):
        nonce = q.get("nonce", "")
        if not re.fullmatch(benchd_client.NONCE_RE, nonce):
            return 400, {"error": "nonce: 16 to 64 hex digits"}
        return 200, svc.whoami(nonce)

    def get_job(h, q):
        job = svc.jobs.get(q["id"])
        return (200, job) if job else (404, {"error": "no such job"})

    def post_lock(h, b):
        return svc.lock.acquire(b.get("owner"), b.get("ttl_s", 900), b.get("wait_s", 0), b.get("pid"), b.get("note", ""),
                                b.get("token"))

    def post_shutdown(h, b):
        if not h.local():
            return 403, {"error": "only from this PC"}
        threading.Timer(0.3, svc.stop).start()      # the answer goes out first
        return 200, {"stopping": True}

    def held(fn):
        """A changing request: refused (423) while another owner holds the lock, unless force (written as an event)."""
        def run(h, b):
            owner, force = b.get("owner"), bool(b.get("force"))
            holder = svc.lock.allows(owner, b.get("token"), force)
            if holder:
                return 423, {"error": "the bench is held by %s" % holder, "holder": holder}
            if force and owner != (svc.lock.view()["holder"] or {}).get("owner"):
                svc.store.event({"type": "lock", "action": "overridden", "by": owner or "admin", "path": h.route_path})
            return fn(b, owner)
        return run

    def post_cmd(b, owner):
        target, cmd = b.get("target", "lyrat"), (b.get("cmd") or "").strip()
        if not cmd:
            return 400, {"error": "cmd is needed"}
        return svc.command(target, cmd, owner)

    handlers = {
        ("GET", "/"): page, ("GET", "/index.html"): page, ("GET", "/favicon.ico"): favicon,
        ("GET", "/status"): lambda h, q: (200, svc.status()),
        ("GET", "/logs"): get_logs, ("GET", "/tail"): get_tail, ("GET", "/events"): get_events,
        ("GET", "/lock"): lambda h, q: (200, svc.lock.view()),
        ("GET", "/jobs"): lambda h, q: (200, {"jobs": svc.jobs.list()}),
        ("GET", "/jobs/{id}"): get_job,
        ("GET", "/api/routes"): lambda h, q: (200, {"version": VERSION, "routes": ROUTES, "actions": ACTIONS}),
        ("GET", "/api/whoami"): get_whoami,
        ("POST", "/lock"): post_lock,
        ("POST", "/lock/renew"): lambda h, b: svc.lock.renew(b.get("owner"), b.get("token"), b.get("ttl_s")),
        ("POST", "/lock/release"): lambda h, b: svc.lock.release(b.get("owner"), b.get("token"), bool(b.get("force"))),
        ("POST", "/cmd"): held(post_cmd),
        ("POST", "/ota"): held(lambda b, owner: ota_job(svc, b, owner)),
        ("POST", "/action"): held(lambda b, owner: action(svc, b, owner)),
        ("POST", "/shutdown"): post_shutdown,
    }
    rows = {(r["method"], r["path"]): r for r in ROUTES}
    if set(rows) != set(handlers):
        raise RuntimeError("benchd ROUTES and handlers differ: %s" % sorted(set(rows) ^ set(handlers)))

    def find(method, path):
        """The row of ROUTES and the values of its {name} parts, or (None, None)."""
        if (method, path) in rows:
            return rows[(method, path)], {}
        for (m, p), row in rows.items():
            if m == method and "{" in p:
                head = p[:p.index("{")]
                if path.startswith(head) and len(path) > len(head) and "/" not in path[len(head):]:
                    return row, {p[p.index("{") + 1:p.index("}")]: path[len(head):]}
        return None, None

    class Handler(BaseHTTPRequestHandler):
        server_version = "benchd/" + VERSION
        route_path = None

        def log_message(self, *a):
            pass

        def reply(self, code, obj, ctype="application/json; charset=utf-8"):
            if obj is None:
                self.send_response(code)
                self.end_headers()
                return
            body = obj if isinstance(obj, bytes) else json.dumps(obj, ensure_ascii=False, indent=1).encode("utf-8")
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(body)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            if ctype.startswith("text/html"):
                self.send_header("Content-Security-Policy", "default-src 'self'; script-src 'unsafe-inline' 'self'; "
                                                            "style-src 'unsafe-inline' 'self'; connect-src 'self'")
            self.end_headers()
            self.wfile.write(body)

        def local(self):
            return self.client_address[0].startswith("127.") or self.client_address[0] == "::1"

        def do_GET(self):
            u = urlparse(self.path)
            q = {k: v[-1] for k, v in parse_qs(u.query).items()}
            row, parts = find("GET", u.path)
            if row is None:
                return self.reply(404, {"error": "unknown path"})
            q.update(parts)
            try:
                return self.reply(*handlers[("GET", row["path"])](self, q))
            except (ValueError, re.error) as e:
                return self.reply(400, {"error": str(e)})

        def do_POST(self):
            u = urlparse(self.path)
            if not self.local():
                if not svc.args.lan_control:
                    return self.reply(403, {"error": "control only from this PC (benchd --lan-control allows the LAN)"})
                given = self.headers.get("X-Bench-Token") or ""
                if not svc.lan_token or not hmac.compare_digest(given.encode(), svc.lan_token.encode()):
                    return self.reply(401, {"error": "the LAN token is needed (header X-Bench-Token; bench.py phone-link "
                                                     "gives it to the phone)" if not given else "wrong LAN token"})
            if self.headers.get("X-Bench") != "1":
                return self.reply(403, {"error": "header X-Bench: 1 is needed"})
            row, _ = find("POST", u.path)
            if row is None:
                return self.reply(404, {"error": "unknown path"})
            if not self.local() and not row.get("lan"):
                return self.reply(403, {"error": "only from this PC"})
            try:
                n = int(self.headers.get("Content-Length") or 0)
                body = json.loads(self.rfile.read(n).decode("utf-8") or "{}") if n else {}
                if not isinstance(body, dict):
                    raise ValueError("a JSON object is needed")
            except ValueError as e:
                return self.reply(400, {"error": "bad JSON: %s" % e})
            self.route_path = row["path"]
            try:
                return self.reply(*handlers[("POST", row["path"])](self, body))
            except (ValueError, TypeError) as e:
                return self.reply(400, {"error": str(e)})

    return Handler


def ota_job(svc, body, owner):
    board = body.get("board", "both")
    if board not in ("lyrat", "s3", "both"):
        return 400, {"error": "board: lyrat, s3 or both"}
    argv = [str(BENCH / "fw.py"), "flash", "--board", board]
    if body.get("image"):
        if board == "both":
            return 400, {"error": "an image is for one board"}
        if not Path(body["image"]).is_file():
            return 400, {"error": "no such image file"}
        argv += ["--image", body["image"]]
    elif body.get("variant"):
        argv += ["--variant", str(body["variant"])]
    if body.get("via") in ("auto", "wifi", "uart"):
        argv += ["--via", body["via"]]
    return 202, svc.jobs.start("flash-" + board, argv, owner or "admin")


def action(svc, body, owner):
    name = body.get("name")
    owner = owner or "admin"
    if name not in ACTIONS:
        return 400, {"error": "unknown action %s" % name}
    return ACTION_RUN[name](svc, body, owner)


def bt_mode(svc, body, owner):
    if not svc.args.bt_mode_cmd:
        return 400, {"error": "this firmware has no Bluetooth mode command (benchd --bt-mode-cmd)"}
    mode = str(body.get("mode", ""))
    if not re.fullmatch(r"[A-Za-z0-9_]{1,16}", mode):
        return 400, {"error": "mode: letters and digits"}
    return svc.command("lyrat", svc.args.bt_mode_cmd.format(mode=mode), owner)


ACTION_RUN = {
    "reboot_lyrat": lambda svc, body, owner: svc.command("lyrat", "reboot 1", owner),
    "restart_s3": lambda svc, body, owner: svc.command("s3", "restart", owner),
    "bt_mode": bt_mode,
    "flash_both": lambda svc, body, owner: ota_job(svc, {"board": "both"}, owner),
    "call_probe": lambda svc, body, owner: (202, svc.jobs.start("call_probe", [str(BENCH / "call_check.py"), "--probe",
                                                                                "1"], owner)),
}
assert set(ACTION_RUN) == set(ACTIONS), "benchd ACTIONS and ACTION_RUN differ"


