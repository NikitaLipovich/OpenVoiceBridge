class SpecError(Exception):
    pass


def templates_of(spec):
    """(where, template, context) of every template: context "status", "item:<list>", "response" or "job"."""
    out = [("header", spec["header"], "status"), ("texts.lock_other", spec["texts"]["lock_other"], "status")]
    for k in ("job_started", "done", "refused"):
        out.append(("texts." + k, spec["texts"][k], "response"))
    for k in ("job_state", "job_ended"):
        out.append(("texts." + k, spec["texts"][k], "job"))
    for panel in spec["panels"]:
        for f in panel["fields"]:
            ctx = "item:" + f["list"] if f.get("list") else "status"
            out.append(("field %s label" % f["id"], f["label"], ctx))
            for i, c in enumerate(f["cases"]):
                out.append(("field %s case %d" % (f["id"], i), c.get("text", ""), ctx))
    for a in spec["actions"]:
        for k in ("confirm", "confirm2", "unavailable_text"):
            if a.get(k):
                out.append(("action %s %s" % (a["id"], k), a[k], "status"))
        for k, v in a.get("body", {}).items():
            if isinstance(v, str):
                out.append(("action %s body.%s" % (a["id"], k), v, "status"))
        for kind in ("ok", "fail"):
            for i, c in enumerate(a.get("result", {}).get(kind, [])):
                out.append(("action %s result.%s %d" % (a["id"], kind, i), c.get("text", ""), "response"))
    return out


def conditions_of(spec):
    out = []
    for panel in spec["panels"]:
        for f in panel["fields"]:
            ctx = "item:" + f["list"] if f.get("list") else "status"
            for i, c in enumerate(f["cases"]):
                out += [("field %s case %d" % (f["id"], i), cond, ctx) for cond in c.get("if", [])]
    for a in spec["actions"]:
        for k in ("visible_if", "available_if"):
            out += [("action %s %s" % (a["id"], k), cond, "status") for cond in a.get(k, [])]
        for kind in ("ok", "fail"):
            for i, c in enumerate(a.get("result", {}).get(kind, [])):
                out += [("action %s result.%s %d" % (a["id"], kind, i), cond, "response") for cond in c.get("if", [])]
    return out


def validate(spec):
    """Structural errors of the spec (a list of strings)."""
    err = []
    for key in ("spec_version", "title", "owner", "poll_ms", "texts", "header", "panels", "actions", "feeds"):
        if key not in spec:
            err.append("spec: no %s" % key)
    if err:
        return err
    for k in ("no_service", "updated", "lock_other", "job_started", "job_state", "job_running", "job_ended", "done",
              "refused", "unknown_route", "busy"):
        if k not in spec["texts"]:
            err.append("texts: no %s" % k)
    ids = set()
    groups = {p.get("actions") for p in spec["panels"] if p.get("actions")}
    for panel in spec["panels"]:
        for f in panel.get("fields", []):
            if f["id"] in ids:
                err.append("field id %s twice" % f["id"])
            ids.add(f["id"])
            if not f.get("cases"):
                err.append("field %s: no cases" % f["id"])
            for c in f.get("cases", []):
                if c.get("color", "") not in COLORS:
                    err.append("field %s: color %r (one of %s)" % (f["id"], c.get("color"), COLORS))
    aids = set()
    for a in spec["actions"]:
        if a["id"] in aids:
            err.append("action id %s twice" % a["id"])
        aids.add(a["id"])
        if not re.fullmatch(r"[a-z][a-z0-9_]*", a["id"]):
            err.append("action id %s: lower case letters, digits, _" % a["id"])
        for k in ("label", "group", "method", "endpoint", "lan_control", "requires_lock", "danger"):
            if k not in a:
                err.append("action %s: no %s" % (a["id"], k))
        if a.get("group") not in groups:
            err.append("action %s: group %s is in no panel" % (a["id"], a.get("group")))
        if a.get("method") != "POST":
            err.append("action %s: method %s (actions are POST)" % (a["id"], a.get("method")))
        for p in a.get("params", []):
            err += param_errors("action %s" % a["id"], p)
    for fd in spec["feeds"]:
        if fd.get("kind") not in ("events", "tail"):
            err.append("feed %s: kind %s (events or tail)" % (fd.get("id"), fd.get("kind")))
        if fd.get("method") != "GET":
            err.append("feed %s: method %s (feeds are GET)" % (fd.get("id"), fd.get("method")))
        for p in fd.get("params", []):
            err += param_errors("feed %s" % fd["id"], p)
    for where, tpl, _ in templates_of(spec):
        for m in PLACEHOLDER.finditer(tpl or ""):
            if m.group(2) and m.group(2) not in FORMATS:
                err.append("%s: format %s (one of %s)" % (where, m.group(2), ", ".join(FORMATS)))
    for where, cond, _ in conditions_of(spec):
        if cond.get("op") not in OPS:
            err.append("%s: op %s (one of %s)" % (where, cond.get("op"), ", ".join(OPS)))
        if cond.get("op") in ("eq", "ne", "lt", "le", "gt", "ge") and "value" not in cond:
            err.append("%s: op %s needs a value" % (where, cond.get("op")))
    return err


def param_errors(where, p):
    err = []
    if p.get("type") not in ("text", "enum", "int"):
        err.append("%s param %s: type %s (text, enum, int)" % (where, p.get("name"), p.get("type")))
    if p.get("type") == "enum":
        vals = [c[0] for c in p.get("choices", [])]
        if not vals:
            err.append("%s param %s: an enum without choices" % (where, p.get("name")))
        if p.get("default", vals[0] if vals else None) not in vals:
            err.append("%s param %s: default %r is not a choice" % (where, p.get("name"), p.get("default")))
    return err


# --- generation: the web page --------------------------------------------------------------------------------------

def h(text):
    return (str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;"))


def web_param(owner_id, p):
    pid = "%s-%s" % (owner_id, p["name"])
    if p["type"] == "enum":
        opts = "".join('<option value="%s"%s>%s</option>' % (h(v), " selected" if v == p.get("default", "") else "", h(lbl))
                       for v, lbl in p["choices"])
        return '<select id="%s" title="%s">%s</select>' % (h(pid), h(p.get("label", "")), opts)
    kind = "number" if p["type"] == "int" else "text"
    return '<input id="%s" type="%s" size="%d" value="%s" placeholder="%s" title="%s">' % (
        h(pid), kind, 32 if p["name"] == "grep" else 10, h(p.get("default", "")), h(p.get("placeholder", "")),
        h(p.get("label", "")))


def web_actions(spec, group):
    acts = [a for a in spec["actions"] if a["group"] == group]
    rows = sorted({a.get("row", 1) for a in acts})
    out = []
    for r in rows:
        items = []
        for a in [a for a in acts if a.get("row", 1) == r]:
            params = "".join(web_param("a-" + a["id"], p) for p in a.get("params", []))
            btn = '<button id="a-%s" data-act="%s"%s>%s</button>' % (h(a["id"]), h(a["id"]),
                                                                     ' class="danger"' if a["danger"] else "", h(a["label"]))
            items.append('<span class="act" id="w-%s">%s%s</span>' % (h(a["id"]), params, btn))
        out.append('    <div class="acts">%s</div>' % "".join(items))
    return out


def web_markup(spec):
    m = ['<header>',
         '  <h1>%s</h1>' % h(spec["title"]),
         '  <span class="mute" id="svc">служба: …</span>',
         '  <span class="mute" id="updated"></span>',
         '  <span class="mute" id="tokenbox" hidden>токен управления: <input id="token" type="password" size="18">'
         '<button id="tokensave">запомнить</button></span>',
         '</header>',
         '<main>']
    for panel in spec["panels"]:
        m.append('  <section id="p-%s">' % h(panel["id"]))
        m.append('    <h2>%s</h2>' % h(panel["title"]))
        for f in panel["fields"]:
            if f.get("list"):
                m.append('    <div id="l-%s"></div>' % h(f["id"]))
            else:
                m.append('    <div class="row" id="f-%s"><span class="k">%s</span><span class="v">…</span></div>'
                         % (h(f["id"]), h(f["label"])))
        if panel.get("actions"):
            m += web_actions(spec, panel["actions"])
        if panel.get("results"):
            m.append('    <div id="msg"></div>')
            m.append('    <pre id="jobout"></pre>')
        m.append('  </section>')
    for fd in spec["feeds"]:
        m.append('  <section class="wide" id="feed-%s">' % h(fd["id"]))
        m.append('    <h2>%s</h2>' % h(fd["title"]))
        filters = "".join(web_param("q-" + fd["id"], p) for p in fd.get("params", []))
        if fd["kind"] == "tail":
            filters += ('<label><input type="checkbox" id="pause-%s"> пауза</label><button id="clear-%s">очистить</button>'
                        % (h(fd["id"]), h(fd["id"])))
        m.append('    <div class="filters">%s</div>' % filters)
        if fd["kind"] == "events":
            head = "".join("<th>%s</th>" % h(c) for c in fd["columns"])
            m.append('    <div class="events"><table><thead><tr>%s</tr></thead><tbody id="rows-%s"></tbody></table></div>'
                     % (head, h(fd["id"])))
        else:
            m.append('    <pre id="rows-%s"></pre>' % h(fd["id"]))
        m.append('  </section>')
    m.append('</main>')
    return "\n".join(m)


def gen_web(spec, template_text):
    if "<!--@MARKUP@-->" not in template_text or "/*@SPEC@*/null" not in template_text:
        raise SpecError("the template has no <!--@MARKUP@--> or /*@SPEC@*/null")
    data = json.dumps(spec, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    out = template_text.replace("<!--@MARKUP@-->", web_markup(spec)).replace("/*@SPEC@*/null", data)
    out = out.replace("<!--@GENERATED@-->", "<!-- %s (spec_version %s) -->" % (GENERATED, spec["spec_version"]))
    return out


# --- generation: Java -----------------------------------------------------------------------------------------------

def js(s):
    """A Java string literal (UTF-8 source), or null."""
    if s is None:
        return "null"
    s = str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t")
    return '"%s"' % s


def jval(v):
    if v is None:
        return "null"
    if v is True:
        return "Boolean.TRUE"
    if v is False:
        return "Boolean.FALSE"
    if is_num(v):
        return "Double.valueOf(%r)" % float(v)
    return js(v)


def jconds(conds):
    if not conds:
        return "null"
    return "new Cond[]{%s}" % ", ".join("new Cond(%s, %s, %s)" % (js(c["path"]), js(c["op"]), jval(c.get("value")))
                                         for c in conds)


def jcases(cases, indent):
    if not cases:
        return "null"
    pad = " " * indent
    rows = "".join("%s    new Case(%s, %s, %s),\n" % (pad, jconds(c.get("if")), js(c.get("text", "")), js(c.get("color", "")))
                   for c in cases)
    return "new Case[]{\n" + rows + pad + "}"


def jparams(params):
    if not params:
        return "null"
    items = []
    for p in params:
        choices = "null"
        if p.get("choices"):
            choices = "new String[][]{%s}" % ", ".join("{%s, %s}" % (js(v), js(lbl)) for v, lbl in p["choices"])
        items.append("new Param(%s, %s, %s, %s, %s, %s)" % (js(p["name"]), js(p.get("label", "")), js(p["type"]), choices,
                                                            js(p.get("default", "")), js(p.get("placeholder", ""))))
    return "new Param[]{%s}" % ", ".join(items)


def jstrings(items):
    return "new String[]{%s}" % ", ".join(js(x) for x in items) if items is not None else "null"


