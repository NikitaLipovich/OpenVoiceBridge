# --- the template language: the reference; the same rules are in bench_ui_web.tmpl.html (JS) and BenchTemplate.java ---
FORMATS = ("int", "mb1", "mb0", "hhmm", "hms", "opt_comma", "owners", "json")
OPS = ("eq", "ne", "lt", "le", "gt", "ge", "truthy", "falsy", "empty", "nonempty")
COLORS = ("", "ok", "warn", "bad")
PLACEHOLDER = re.compile(r"\{([^{}|]+)(?:\|([a-z_0-9]+))?\}")
NUMERIC = re.compile(r"^-?\d+(\.\d+)?$")
MISSING = "—"


def is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def to_num(v):
    """A number, or a string that is one (the S3's stat fields are strings); else None."""
    if is_num(v):
        return float(v)
    if isinstance(v, str) and NUMERIC.match(v):
        return float(v)
    return None


def fixed(x, digits):
    """x with this many decimals, ties away from zero on the exact binary value (= JS toFixed, Java BigDecimal HALF_UP)."""
    s = str(Decimal(x).quantize(Decimal(1).scaleb(-digits), rounding=ROUND_HALF_UP))
    if s.startswith("-") and not s.strip("-0."):
        s = s[1:]
    return s


def num_str(x):
    x = float(x)
    if x.is_integer() and abs(x) < 1e15:
        return str(int(x))
    s = fixed(x, 3).rstrip("0").rstrip(".")
    return s


def json_str(v):
    """Compact JSON with the numbers as num_str: the same text in Python, JS and Java."""
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if is_num(v):
        return num_str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, list):
        return "[" + ",".join(json_str(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ",".join(json.dumps(str(k), ensure_ascii=False) + ":" + json_str(x) for k, x in v.items()) + "}"
    return json.dumps(str(v), ensure_ascii=False)


def value_str(v):
    if v is None:
        return MISSING
    if v is True:
        return "да"
    if v is False:
        return "нет"
    if is_num(v):
        return num_str(v)
    if isinstance(v, (list, dict)):
        return json_str(v)
    return str(v)


def is_empty(v):
    return v is None or v == "" or (isinstance(v, (list, dict)) and not v)


def truthy(v):
    if v is None or v is False or v == "":
        return False
    if is_num(v):
        return v != 0
    if isinstance(v, (list, dict)):
        return bool(v)
    return True


def resolve(path, ctx, vars_):
    """The value at a dotted path; "$name" paths come from vars_ ($device, $owner, $param.x, ...). None when absent."""
    parts = path.strip().split(".")
    if parts[0].startswith("$"):
        cur = vars_.get(parts[0][1:]) if vars_ else None
        parts = parts[1:]
    else:
        cur = ctx
    for p in parts:
        if isinstance(cur, dict):
            cur = cur.get(p)
        elif isinstance(cur, list) and p.isdigit() and int(p) < len(cur):
            cur = cur[int(p)]
        else:
            return None
    return cur


def fmt(v, name):
    if name is None:
        return value_str(v)
    if name == "int":
        n = to_num(v)
        return MISSING if n is None else num_str(math.floor(n + 0.5))
    if name in ("mb1", "mb0"):
        n = to_num(v)
        return MISSING if n is None else fixed(n / 1048576.0, 1 if name == "mb1" else 0)
    if name in ("hhmm", "hms"):
        end = 16 if name == "hhmm" else 19
        return v[11:end] if isinstance(v, str) and len(v) >= end else MISSING
    if name == "opt_comma":
        return "" if is_empty(v) or not truthy(v) else ", " + value_str(v)
    if name == "owners":
        if not isinstance(v, list):
            return ""
        return ", ".join(value_str(x.get("owner")) for x in v if isinstance(x, dict))
    if name == "json":
        return json_str(v)
    raise ValueError("unknown format %s" % name)


def render(tpl, ctx, vars_=None):
    if tpl is None:
        return ""
    return PLACEHOLDER.sub(lambda m: fmt(resolve(m.group(1), ctx, vars_), m.group(2)), tpl)


def eq(a, b):
    """Numbers (and numeric strings) by value; else the same type and value; null only equals null."""
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    na, nb = to_num(a), to_num(b)
    if na is not None and nb is not None:
        return na == nb
    if a is None or b is None:
        return a is None and b is None
    return type(a) is type(b) and a == b


def holds(conds, ctx, vars_=None):
    for c in conds or []:
        v = resolve(c["path"], ctx, vars_)
        op, want = c["op"], c.get("value")
        if op == "truthy":
            ok = truthy(v)
        elif op == "falsy":
            ok = not truthy(v)
        elif op == "empty":
            ok = is_empty(v)
        elif op == "nonempty":
            ok = not is_empty(v)
        elif op == "eq":
            ok = eq(v, want)
        elif op == "ne":
            ok = not eq(v, want)
        else:
            a, b = to_num(v), to_num(want)
            if a is None or b is None:
                ok = False
            else:
                ok = {"lt": a < b, "le": a <= b, "gt": a > b, "ge": a >= b}[op]
        if not ok:
            return False
    return True


def pick(cases, ctx, vars_=None):
    """(text, color) of the first case whose conditions hold; ("", "") when none does."""
    for c in cases or []:
        if holds(c.get("if"), ctx, vars_):
            return render(c.get("text", ""), ctx, vars_), c.get("color", "")
    return "", ""


def render_panel(spec, status, device="страница"):
    """Everything the panel shows for one status: the reference output of the web and Java renderers."""
    vars_ = {"device": device, "owner": spec["owner"]}
    out = {"header": render(spec["header"], status, vars_), "fields": [], "actions": []}
    for panel in spec["panels"]:
        for f in panel["fields"]:
            if f.get("list"):
                items = resolve(f["list"], status, vars_)
                for i, item in enumerate(items if isinstance(items, list) else []):
                    text, color = pick(f["cases"], item, vars_)
                    out["fields"].append({"id": "%s.%d" % (f["id"], i), "label": render(f["label"], item, vars_),
                                          "text": text, "color": color})
            else:
                text, color = pick(f["cases"], status, vars_)
                out["fields"].append({"id": f["id"], "label": render(f["label"], status, vars_), "text": text,
                                      "color": color})
    for a in spec["actions"]:
        pv = dict(vars_, param={p["name"]: p.get("default", "") for p in a.get("params", [])})
        out["actions"].append({"id": a["id"], "visible": holds(a.get("visible_if"), status, pv),
                               "available": holds(a.get("available_if"), status, pv),
                               "confirm": render(a.get("confirm"), status, pv),
                               "confirm2": render(a.get("confirm2"), status, pv),
                               "body": json.loads(render_body(a.get("body", {}), status, pv))})
    out["lock_other"] = render(spec["texts"]["lock_other"], status, vars_)
    return out


def render_body(body, ctx, vars_):
    """The fixed body of an action with its string values rendered, as compact JSON."""
    return json_str({k: render(v, ctx, vars_) if isinstance(v, str) else v for k, v in body.items()})


