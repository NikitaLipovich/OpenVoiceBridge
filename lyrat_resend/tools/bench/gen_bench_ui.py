def first_diff(a, b):
    la, lb = a.splitlines(), b.splitlines()
    for i, (x, y) in enumerate(zip(la, lb)):
        if x != y:
            return "line %d: on disk %r, from the spec %r" % (i + 1, x[:100], y[:100])
    return "length: on disk %d lines, from the spec %d" % (len(la), len(lb))


def load_spec(path):
    try:
        spec = json.loads(Path(path).read_text(encoding="utf-8"))
    except ValueError as e:
        raise SpecError("%s: bad JSON: %s" % (path, e))
    errs = validate(spec)
    if errs:
        raise SpecError("\n".join(errs))
    return spec


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except (AttributeError, ValueError):
            pass
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0], formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing, compare (a)-(d)")
    ap.add_argument("--strict", action="store_true", help="with --check: (d) is an error, not a warning")
    ap.add_argument("--status-file", help="with --check: a /status sample instead of the live benchd + simulator")
    ap.add_argument("--status-url", help="with --check: /status of this benchd (http://host:port)")
    ap.add_argument("--no-live", action="store_true", help="with --check: leave out (c)")
    ap.add_argument("--render", metavar="STATUS_JSON", help="print the rendered panel for this status sample")
    ap.add_argument("--device", default="страница", help="with --render: the $device word")
    ap.add_argument("--spec", default=str(SPEC))
    ap.add_argument("--template", default=str(TEMPLATE))
    ap.add_argument("--web-out", default=str(WEB_OUT))
    ap.add_argument("--java-out", default=str(JAVA_OUT))
    ap.add_argument("--benchd", default=str(BENCHD))
    args = ap.parse_args(argv)
    try:
        spec = load_spec(args.spec)
        if args.render:
            sample = json.loads(Path(args.render).read_text(encoding="utf-8"))
            print(json.dumps(render_panel(spec, sample, args.device), ensure_ascii=False, indent=1))
            return 0
        web = gen_web(spec, Path(args.template).read_text(encoding="utf-8"))
        java = gen_java(spec)
        routes, actions = benchd_tables(args.benchd)
    except SpecError as e:
        print("spec error:\n%s" % e, file=sys.stderr)
        return 1
    except OSError as e:
        print("cannot read: %s" % e, file=sys.stderr)
        return 2
    b_err, d_warn = check_routes(spec, routes, actions)
    if not args.check:
        if b_err:
            print("\n".join(b_err), file=sys.stderr)
            print("not written: the spec does not fit benchd", file=sys.stderr)
            return 1
        for path, text in ((args.web_out, web), (args.java_out, java)):
            Path(path).write_bytes(text.encode("utf-8"))
            print("wrote %s" % path)
        for w in d_warn:
            print("WARN " + w)
        return 0

    errors, warnings = [], []
    for name, path, text in (("web page", args.web_out, web), ("Android BenchSpec.java", args.java_out, java)):
        try:
            # Line ends do not count: git may check the files out with CRLF (core.autocrlf).
            disk = Path(path).read_bytes().decode("utf-8").replace("\r\n", "\n")
        except OSError:
            errors.append("(a) %s: %s is missing" % (name, path))
            continue
        if disk != text:
            errors.append("(a) %s %s differs from the spec: %s (run gen_bench_ui.py)" % (name, Path(path).name,
                                                                                       first_diff(disk, text)))
    errors += b_err
    (errors if args.strict else warnings).extend(d_warn)
    unverified = []
    if not args.no_live:
        try:
            if args.status_file:
                sample = json.loads(Path(args.status_file).read_text(encoding="utf-8"))
            elif args.status_url:
                sample = get(args.status_url.rstrip("/"), "/status")
            else:
                sample = live_status()
        except Exception as e:      # noqa: BLE001 - any failure of the live part means (c) could not be checked
            print("FAIL (c) could not get a /status sample: %s" % e, file=sys.stderr)
            return 2
        c_err, unverified = check_status(spec, sample)
        errors += c_err
    for e in errors:
        print("FAIL " + e)
    for w in warnings:
        print("WARN " + w)
    for u in unverified:
        print("note (c) %s: not in this sample (null or an empty list), not verified" % u)
    print("bench UI: %d actions, %d feeds, %d status paths; %s" % (
        len(spec["actions"]), len(spec["feeds"]), len(status_paths(spec)),
        "%d error(s)" % len(errors) if errors else "spec, generated files and benchd agree"))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
